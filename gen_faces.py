#!/usr/bin/env python3
"""Convert toaster_faces.h (128x64 1-bit Arduino bitmaps) to Faces.swift (32x16 logical rows)."""
import re, sys
src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()
out = ["// Generated by gen_faces.py from toaster_faces.h. Do not edit.", "// Each face: 16 rows, bit 31 = leftmost of 32 logical px.", "let faceRows: [String: [UInt32]] = ["]
for m in re.finditer(r'FACE_(\w+)\[\] = \{(.*?)\};', s, re.S):
    b = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]{2}', m.group(2))]
    assert len(b) == 1024, m.group(1)
    rows = []
    for y in range(16):
        v = 0
        for x in range(32):
            px, py = x * 4, y * 4
            if b[py * 16 + px // 8] >> (7 - px % 8) & 1:
                v |= 1 << (31 - x)
        rows.append("0x%08X" % v)
    out.append('  "%s": [%s],' % (m.group(1), ", ".join(rows)))
out.append("]")
open(dst, "w").write("\n".join(out) + "\n")
